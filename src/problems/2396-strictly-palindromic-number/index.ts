/**
 * 2396. Strictly Palindromic Number
 *
 * Returns whether `n` (at least 4) is a palindrome in every base from 2
 * to `n - 2`.
 *
 * In base `n - 2`, `n` is written "12", so none is.
 *
 * @see https://leetcode.com/problems/strictly-palindromic-number/
 * @difficulty Medium
 * @timeComplexity O(1)
 * @spaceComplexity O(1)
 *
 * @example
 * strictlyPalindromicNumber(9); // false
 */
export const strictlyPalindromicNumber = (_n: number): boolean => false;
