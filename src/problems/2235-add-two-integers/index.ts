/**
 * 2235. Add Two Integers
 *
 * Returns `num1 + num2`.
 *
 * @see https://leetcode.com/problems/add-two-integers/
 * @difficulty Easy
 * @timeComplexity O(1)
 * @spaceComplexity O(1)
 *
 * @example
 * addTwoIntegers(12, 5); // 17
 */
export const addTwoIntegers = (num1: number, num2: number): number =>
	num1 + num2;
