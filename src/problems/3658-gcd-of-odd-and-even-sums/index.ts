/**
 * 3658. GCD of Odd and Even Sums
 *
 * Returns the gcd of the sum of the first `n` odd numbers and the sum of
 * the first `n` even numbers.
 *
 * Those sums are n² and n(n + 1), and n and n + 1 are coprime, so the gcd
 * is n.
 *
 * @see https://leetcode.com/problems/gcd-of-odd-and-even-sums/
 * @difficulty Easy
 * @timeComplexity O(1)
 * @spaceComplexity O(1)
 *
 * @example
 * gcdOfOddAndEvenSums(4); // 4
 */
export const gcdOfOddAndEvenSums = (n: number): number => n;
